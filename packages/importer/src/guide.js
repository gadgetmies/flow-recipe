// policy, and the prompt builders (first request and repair rounds).

import { readFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
/** Repository root (packages/importer/src → ../../..). */
export const REPO_ROOT = resolve(here, '..', '..', '..')
export const GUIDE_PATH = join(REPO_ROOT, 'RECIPE.spec.md')
export const RECIPES_DIR = join(REPO_ROOT, 'packages', 'server', 'src', 'recipes')
export const OPERATIONS_PATH = join(RECIPES_DIR, 'operations.xml')

/** The v2 authoring guide (RECIPE.spec.md at the repository root; env FLOW_RECIPE_GUIDE overrides the path). */
export function loadGuide(path = process.env.FLOW_RECIPE_GUIDE || GUIDE_PATH) {
  return readFileSync(path, 'utf8')
}

/** The operation catalogue XML (packages/server/src/recipes/operations.xml; env FLOW_OPERATIONS_XML overrides). */
export function loadOperationsXml(path = process.env.FLOW_OPERATIONS_XML || OPERATIONS_PATH) {
  return readFileSync(path, 'utf8')
}

function fmtSeconds(s) {
  if (!s) return '0'
  if (s % 3600 === 0) return `${s / 3600}h`
  if (s >= 120 && s % 60 === 0) return `${s / 60}min`
  return `${s}s`
}

function arity(min, max) {
  const lo = min === undefined || min === null ? 0 : min
  if (max === undefined || max === null) return `${lo}+`
  return lo === max ? `${lo}` : `${lo}-${max}`
}

/** Operations generated by the scheduler itself; recipes never use them. */
const INTERNAL_OPERATIONS = new Set(['gather'])

/**
 * Compact text table of the catalogue, one operation per line:
 * `name — Title | in 1-2 → out 1 | options: amount* numeric | time: per-unit 20s + 5s/unit, passive from duration |
 *  attention monitored | station hob | requires knife | soil wash | expand bake-in-oven | urgency timed`
 * @param {object} catalogue from loadCatalogue
 */
export function catalogueSummary(catalogue) {
  const lines = []
  for (const name of Object.keys(catalogue || {}).sort()) {
    if (INTERNAL_OPERATIONS.has(name)) continue
    const op = catalogue[name]
    const parts = [`${name}${op.title && op.title !== name ? ` — ${op.title}` : ''}`]
    parts.push(`in ${arity(op.minInputs, op.maxInputs)} → out ${arity(op.minOutputs, op.maxOutputs)}${op.requiresTools ? ', needs a tool' : ''}`)
    const opts = Object.entries(op.options || {}).map(([k, o]) => `${k}${o.required ? '*' : ''} ${o.type || 'numeric'}${o.defaultUnit ? ` (${o.defaultUnit})` : ''}`)
    if (opts.length) parts.push(`options: ${opts.join(', ')}`)
    const t = op.time || {}
    let time = t.model || 'fixed'
    if (t.model === 'per-unit') time += ` ${fmtSeconds(t.active)} + ${fmtSeconds(t.perUnit)}/unit`
    else if (t.model === 'sub-linear') time += ` ${fmtSeconds(t.active)} + ${fmtSeconds(t.perUnit)}·√units`
    else time += ` ${fmtSeconds(t.active)}`
    if (t.passiveFrom === 'duration') time += ', passive = duration option'
    else if (t.passiveFrom) time += `, passive = ${t.passiveFrom.replace('formula:', '')} formula from temperature`
    else if (t.passive) time += `, passive ${fmtSeconds(t.passive)}`
    parts.push(`time: ${time}`)
    if (op.attention && op.attention !== 'attended') parts.push(op.attention)
    if (op.station && op.station !== 'counter') parts.push(`station ${op.station}`)
    if (op.requires && op.requires.length) parts.push(`requires ${op.requires.join(' ')}`)
    if (op.soil && op.soil !== 'rinse') parts.push(`soil ${op.soil}`)
    if (op.expand) parts.push(`expand ${op.expand}`)
    if (op.completion && op.completion.urgency && op.completion.urgency !== 'relaxed' && (t.passive || t.passiveFrom)) parts.push(`urgency ${op.completion.urgency}`)
    if (op.divisible === 'team') parts.push(`team of ≤${op.maxPeople}`)
    lines.push(parts.join(' | '))
  }
  return lines.join('\n')
}

/**
 * The measurement rules, worded for the LLM. The deterministic converter (metricizeRecipeXml) is the source of truth
 * for every unit conversion, so the model copies the source's amounts and units and never does volume → weight or
 * °F → °C arithmetic itself; the converter converts, rounds and leaves a <!-- converted from … --> note.
 */
export function unitsPolicy({ precisionScale = false } = {}) {
  return [
    'MEASUREMENT RULES (code converts units after you answer; do NOT convert them yourself):',
    '- Copy every amount EXACTLY as the source states it, in the source\'s own units: 1 cup flour → number="1" unit="cup", 2 tbsp butter → unit="tbsp", ½ tsp salt → number="0.5" unit="tsp", 8 oz cream cheese → unit="oz", 1 stick butter → unit="stick", 1 lb potatoes → unit="lb", 200 g sugar → unit="g", 3 dl milk → unit="dl". Temperatures likewise: 350 °F → number="350" unit="fahrenheit", 180 °C → unit="celsius". Pan sizes: value="9x13 inch" or "23 cm" as written.',
    '- Never convert volume to weight, ounces to grams or °F to °C, and never round: a converter with a density table does that deterministically and records what it changed. When the source states a weight, use it verbatim, also when it is in parentheses or side by side ("1 cup (125 g) flour" → number="125" unit="g"; "1.2 kg / 2.4 lb beef" → number="1.2" unit="kg"); only volumes without a weight are left for the converter.',
    '- Nordic, German and French spoons may be copied as written (tl, rkl, tsk, msk, krm, ts, ss, TL, EL, c.à.c, c.à.s): they are metric 5 ml / 15 ml spoons and the converter normalises them; kpl/st/Stk are pieces. Package counts (prk, pkt, can, jar, packet) stay counts: name the package size in the ingredient ("cream, 2 dl carton") or measure the contents in g/ml.',
    '- Use the standard unit spellings: g, kg, ml, dl, l, tsp, tbsp, cup, fl oz, oz, lb, stick, pint, quart, fahrenheit, celsius, inch. Write numbers as plain decimals (0.5, not 1/2 or ½).',
    '- Countable things are pieces (unit "pieces"): eggs, garlic cloves, onions, lemons, gelatine sheets, tortillas. "3 large eggs" → number="3" unit="pieces"; put the size in the ingredient properties (size="large") if the source says so.',
    '- Pinch/dash/sprig/bunch/handful stay counts with that word as the unit (number="1" unit="pinch").',
    precisionScale
      ? '- The cook HAS a precision scale (0.1 g): the converter will weigh small amounts of spices, salt, leavening, extracts and fresh herbs; still write them as the source does (1 tsp), and give their measure tasks a precision-scale tool.'
      : '- The cook has NO precision scale: small amounts (up to 1 tbsp and under 10 g) of spices, salt, leavening, extracts, fresh herbs, starch and the like stay teaspoons/tablespoons; the converter handles it.',
    '- Durations use minutes/hours/seconds.',
  ].join('\n')
}

const ROLE = `You convert recipes from the web into recipe XML (format version 2) for "flow-recipe", a multi-cook kitchen scheduler. The scheduler splits the work between several cooks, runs per-unit work (shaping 24 cookies, filling 12 tortillas) as pipelines, sends things to the oven in rounds limited by sheets and oven capacity, times passive steps (rising, baking, chilling) and plans dish-washing. The quality of the schedule depends entirely on how faithfully and how precisely your XML models the real cooking: every real step, the real durations and temperatures from the text, the real tools and their capacities, and which items are made per unit.`

const SCHEDULER_THINKING = `HOW TO WRITE FOR THE SCHEDULER (think about each point before writing):
1. Steps: one task per real action, in a valid order; use only operations from the catalogue below, with their required options. Use the durations and temperatures stated in the source (bake 12 min at 180 °C → duration 12 minutes, temperature 180 celsius; "chill at least 2 hours" → 2 hours). Do not invent steps the recipe does not need, but do not skip implicit ones (preheat oven, line the sheet, measure every ingredient, cool before frosting).
2. Measuring: every ingredient is measured by a "measure" task with an amount option, once per use (an ingredient used twice gets two measure tasks with distinct ids). Measure into the bowl it goes into when it simply joins a mixture.
3. Unit streams: when work is done per piece (cookies, buns, dumplings, burgers, crepes, portions), split the mass into units with the split operation (parts option = the count) or produce outputs with amount + unit="cookie" etc., and keep the same unit name on every following per-unit output (shape → place on sheet → bake → cool). This is what lets several cooks work in a pipeline. Pick the count from the source yield.
4. Carriers and capacities: declare tools that hold units with a capacity property in that unit (baking sheet capacity 12 cookie, cooling rack 24 cookie, pan 4 pancake), give per-unit oven work the sheet as a reserved tool (bake-in-oven expands into oven rounds), and return the carrier in <outputs> (<tool ref="baking-sheet"/>) on the task that frees it (usually moving units to the rack or plate) so the sheet can be reused for the next round.
5. Reserved tools: a bowl or pot that holds a mixture across several tasks is reserved="true" on each of those tasks; set soil="wash"/"rinse"/"none" on tools so dish-washing is planned realistically (a scale or a towel is soil="none").
6. Holds: put hold (minutes) only on results that degrade, on the result that degrades (whipped cream 30, beaten egg whites 10, warm milk for yeast 10, melted chocolate 15, boiling water 15, cooked pasta 2, fried food 10, shaped dough before baking 30, hot baked goods 10); leave it off for things that keep (cut vegetables, a made sauce, measured dry ingredients).
7. Serving: add <serving temperature="hot|cold|ambient" hold="…"/> matching how the dish is eaten (soup hot hold 10, ice cream cold, cookies ambient). Mark the dish output final="true".
8. Storage: perishables get a storage property (fridge/freezer) on the ingredient (milk, butter, eggs, cream, meat, fish, fresh cheese); butter that must be soft gets an out-of-storage time.
9. Requirements: tasks needing a knife, a hot pan or the oven state requires="…" when the operation does not already require it; long passive steps (rising, chilling, baking, simmering) use operations with a passive part so cooks are free meanwhile.
10. Joins: wrap steps that one cook must do in one go without interruption in <join>.
11. One vessel, several steps: steps done one after another in the same pot or pan (brown the meat, then soften the onions in the fat, then add the liquid) must be linked by data, because a shared tool does not order them. Each step consumes the previous step's output; when the earlier result leaves the pot, give that task an extra output for the used pot (e.g. "pot-with-fond") and make it an input of the next step in that pot.`

const OUTPUT_RULES = `OUTPUT RULES (strict):
- Answer with exactly ONE complete XML document and nothing else: no explanations, no markdown fences, no comments outside the document. Start with <?xml version="1.0" encoding="utf-8"?> and the root <recipe version="2" id="…" ref="SOURCE URL">.
- Ids are kebab-case ASCII, unique across ingredients, tools, outputs and tasks; every input ref must point to an ingredient, a tool or an output produced by an EARLIER task.
- Write ingredient and tool names, titles and instruction text in the language of the source page.
- Use only operations, options and attributes described in the guide and the catalogue. Numbers are plain decimals (0.5, not 1/2).
- XML comments inside the document are fine for noting assumptions (e.g. <!-- source says "a handful", estimated 30 g -->).`

/**
 * Format a Source for the LLM: structured fields first, then the readable text as a fallback.
 * @param {object} source Source
 * @param {{ maxTextChars?: number }} [options]
 */
export function formatSource(source, { maxTextChars } = {}) {
  const s = source || {}
  const lines = []
  if (s.url) lines.push(`Source URL: ${s.url}`)
  if (s.title) lines.push(`Title: ${s.title}`)
  if (s.lang) lines.push(`Page language: ${s.lang}`)
  if (s.yield || s.servings) lines.push(`Yield: ${s.yield || ''}${s.servings ? ` (servings/count: ${s.servings})` : ''}`.trim())
  const t = s.times || {}
  const time = [['prep', 'prep'], ['cook', 'cook'], ['total', 'total']]
    .filter(([k]) => t[k])
    .map(([k, label]) => `${label} ${fmtMinutes(t[k])}`)
  if (time.length) lines.push(`Times: ${time.join(', ')}`)
  if (s.category || s.cuisine) lines.push(`Category: ${[s.category, s.cuisine].filter(Boolean).join(' / ')}`)
  if (s.description) lines.push(`Description: ${s.description}`)
  if (Array.isArray(s.tools) && s.tools.length) lines.push(`Equipment: ${s.tools.join(', ')}`)
  if (s.ingredients && s.ingredients.length) {
    lines.push('', `Ingredients (${s.ingredients.length}):`)
    for (const i of s.ingredients) lines.push(`- ${i}`)
  }
  if (s.steps && s.steps.length) {
    lines.push('', `Steps (${s.steps.length}):`)
    s.steps.forEach((st, i) => lines.push(`${i + 1}. ${st}`))
  }
  const structured = s.structured && s.ingredients && s.ingredients.length && s.steps && s.steps.length
  const limit = maxTextChars !== undefined ? maxTextChars : structured ? 8000 : 30000
  let text = String(s.text || '').trim()
  if (text && limit > 0) {
    if (text.length > limit) text = `${text.slice(0, limit)}\n…(truncated)`
    lines.push(
      '',
      structured
        ? 'Page text (for notes, pan sizes, tips and details the structured data lacks; ignore ads and comments):'
        : 'Page text (no structured recipe data was found; extract the recipe from this, ignoring ads, navigation and comments):',
      '"""',
      text,
      '"""'
    )
  }
  if (s.truncated) lines.push('(The page was larger than the download limit; the end of the page is missing.)')
  return lines.join('\n')
}

function fmtMinutes(seconds) {
  const m = Math.round(seconds / 60)
  if (m >= 60) return `${Math.floor(m / 60)} h${m % 60 ? ` ${m % 60} min` : ''}`
  return `${m} min`
}

/**
 * Build the prompt for the first generation request.
 * @param {object} args { source, guide, catalogueText, precisionScale, servings, notes }
 * @returns {{ system: string, messages: [{ role: 'user', content: string }] }}
 */
export function buildMessages({ source, guide, catalogueText, precisionScale = false, servings = null, notes = null } = {}) {
  const system = [
    ROLE,
    '',
    '=== AUTHORING GUIDE (recipe XML v2) ===',
    String(guide || '').trim(),
    '=== END OF GUIDE ===',
    '',
    '=== OPERATION CATALOGUE (name — title | inputs → outputs | options (* = required, default unit) | time model | attention | station | requires | soil | expansion) ===',
    String(catalogueText || '').trim(),
    '=== END OF CATALOGUE ===',
    '',
    unitsPolicy({ precisionScale }),
    '',
    SCHEDULER_THINKING,
    '',
    OUTPUT_RULES,
  ].join('\n')

  const parts = ['Convert this recipe into recipe XML v2.', '', formatSource(source)]
  parts.push('', `Precision scale: ${precisionScale ? 'YES — weigh small amounts in g with 0.1 g resolution' : 'NO — use tsp/tbsp for small amounts of spices, salt, leavening, yeast and extracts'}.`)
  if (servings) {
    parts.push(
      `Servings wanted: ${servings}. ${source && source.servings ? `The source makes ${source.servings}; multiply every amount by ${round(servings / source.servings)} (and unit counts accordingly).` : 'Scale the amounts to this many servings.'}`
    )
  }
  if (notes && String(notes).trim()) parts.push('', 'Notes from the user (follow them):', String(notes).trim())
  if (source && source.url) parts.push('', `Set ref="${source.url}" on the <recipe> element.`)
  parts.push('', 'Reply with the XML document only.')
  return { system, messages: [{ role: 'user', content: parts.join('\n') }] }
}

function round(x) {
  return Math.round(x * 1000) / 1000
}

/**
 * The repair request: what the checker found, most important first, asking for the full corrected document.
 * @param {object} check CheckResult
 * @param {{ attempt?: number, extraErrors?: string[], maxWarnings?: number }} [options]
 */
export function buildRepairMessage(check, { attempt = 1, extraErrors = [], maxWarnings = 12 } = {}) {
  const lines = [`Your XML has problems (repair round ${attempt}). Fix ALL of them and reply with the complete corrected XML document only (no explanations, not a diff).`]
  const errors = [...extraErrors, ...((check && check.errors) || [])]
  if (errors.length) {
    lines.push('', 'Errors (must be fixed):')
    for (const e of errors.slice(0, 40)) lines.push(`- ${e}`)
    if (errors.length > 40) lines.push(`- … and ${errors.length - 40} more`)
  }
  if (check && check.plan && !check.plan.ok) {
    lines.push('', 'Scheduler dry run failed:')
    if (check.plan.error) lines.push(`- ${check.plan.error}`)
    const serious = (check.plan.diagnostics || []).filter((d) => /\[(INVARIANT|DEADLOCK|INCOMPLETE|LATE|SPREAD|NO_[A-Z_]+)\]/.test(d))
    for (const d of serious.slice(0, 8)) lines.push(`- ${d.length > 500 ? `${d.slice(0, 500)}…` : d}`)
  }
  const warnings = importantWarnings(check).slice(0, maxWarnings)
  if (warnings.length) {
    lines.push('', 'Warnings (fix them unless the source really requires it):')
    for (const w of warnings) lines.push(`- ${w}`)
  }
  return lines.join('\n')
}

/** Warnings worth feeding back: validation warnings, unit lint warnings and serious plan diagnostics. */
export function importantWarnings(check) {
  if (!check) return []
  const out = []
  for (const w of check.warnings || []) out.push(w)
  for (const l of check.unitLint || []) if (!l.level || l.level === 'warning') out.push(`${l.taskId ? `Task '${l.taskId}': ` : ''}${l.message}`)
  if (check.plan && check.plan.ok) {
    for (const d of check.plan.diagnostics || []) if (/\[(INVARIANT|DEADLOCK|INCOMPLETE|NO_[A-Z_]+)\]/.test(d)) out.push(`Scheduler: ${d.length > 500 ? `${d.slice(0, 500)}…` : d}`)
  }
  return out
}
